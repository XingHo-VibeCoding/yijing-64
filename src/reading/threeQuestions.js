/**
 * 起卦三问 · 心境线索
 *
 * ============================================================================
 * 为什么是「问用户」而不是「猜用户」
 * ============================================================================
 *
 * 巴纳姆效应（Forer 1948）最容易被误读的一点：**它证明的是「模糊描述会被认领」，
 * 不是「模糊描述算得准」。** 前者让人觉得被说中，后者才是骗人。
 *
 * 所以本项目取的是前者，路径是：
 *   **让用户自己说出处境 → 解读用他自己说过的话回应他。**
 *
 * 这样「精准」的来源不是系统的猜测，而是**他自己的选择**——
 * 他选了「心有未决」，解读就落在「未决」上；这是他说的，不是我们断言的。
 *
 * ⚠️ 由此得出一条硬边界：**选项必须互斥且穷尽常见情形**。
 *   若选项写得像「你既想A又舍不得B」（两头都占），用户当然觉得准 ——
 *   但那是把「精准」做成了「不可证伪」，与产品边界（不假装知道用户的私事）冲突。
 *   → 故每个问题下的选项**各自独立、各自说得通**，不设「全能选项」。
 *
 * ============================================================================
 * 措辞规则（玄妙但不晦涩）
 * ============================================================================
 *
 * 用户要「高深玄妙的表达」，这里把握三条线：
 *   ① **用词取自《周易》**（不造玄词）——「攸」「嘉」「argvament」「BETWEEN」这类真词，
 *      读起来古雅、有出处，但每个字读者都认得。
 *   ② **不装神棍**：不写「天机将显」「命数已定」这类恐吓式玄妙。
 *      玄妙来自**语体的古**，不来自**内容的玄**。
 *   ③ **选项不解释、不诱导**：不写「选这个的人通常很焦虑」——那是替用户下判断。
 *
 * ============================================================================
 * 三问各管什么（三个正交维度，不重复问）
 * ============================================================================
 *
 *   一问 **所向** —— 你此刻要往哪去？     → 决定「落点」的动词（进 / 守 / 转）
 *   二问 **所阻** —— 什么挡着你？         → 决定「共鸣」的落点（人 / 时 / 心 / 力）
 *   三问 **所需** —— 你此刻要的是什么？   → 决定「处境」的收尾（快 / 稳 / 深）
 *
 * 三问组合最多 5×5×5 = 125 种，但**解读不是 125 句**：
 *   每一问各自贡献**一个词**，由 `verdictWith()` 组装进短评 —— 句式固定、词可变。
 *   这样既保证骈句工整与 30 字上限，又让每次读到的都贴着用户自己说的话。
 */

