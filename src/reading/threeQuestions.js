/* ============================================================================
 * 二 · 组装：把用户的选择接进短评
 * ============================================================================ */

/** 取某个问题下用户所选选项的「词」；未答则返回空串。 */
function pickWord(q, answers) {
  if (!answers) return ''
  const picked = answers[q.key]
  if (!picked) return ''
  const opt = q.options.find((o) => o.id === picked)
  return opt ? opt.word : ''
}

/**
 * 三问都答完后，把「所向 / 所阻 / 所需」三个词接进短评。
 *
 * ⭐ **为什么要接**：用户选了「心」「守」「定」，短评里就出现
 *    「守」字与「定」字 —— 他读到时会觉得「这是在说我」。
 *    而这三个字**是他自己按的**，我们没有猜任何事。
 *
 * 追加方式：**接在原短评之后，用「；」分隔**，不改动原句 ——
 * 原句是「卦说什么」（由卦象定，不可变），追加的三个字是「你此刻在做什么」（由他定）。
 * 两层语义分开，来源清楚。
 *
 * ⚠️ **总字数必须仍 ≤ 30**，故追加后统一截断校验（见 `verdictWith` 的注释）。
 *
 * @param {string} base 逐卦专属短评（src/reading/verdict.js 里的 VERDICT）
 * @param {object} answers { going, blocked, need } 各为选项 id
 * @returns {string}
 */
export function appendAnswers(base, answers) {
  if (!base) return ''
  if (!answers) return base

  const going = pickWord(QUESTIONS[0], answers)
  const blocked = pickWord(QUESTIONS[1], answers)
  const need = pickWord(QUESTIONS[2], answers)

  const parts = []
  // 只接已答的部分；一题未答不补空，也不改变另一题的接入方式
  if (going) parts.push(going)
  if (blocked) parts.push(blocked)
  if (need) parts.push(need)

  if (!parts.length) return base

  // 组句：三问各贡献一个「词」，按「所向·所阻·所需」连缀成一句。
  // ⚠️ 这里踩过两次：
  //   ① 三个字硬拼成「守心定」—— 不成话，改为嵌进短句。
  //   ② 把「所阻」当正面宾语 → 「守其人」「进其时」全不通。
  //      「心/时/力」是**障碍**，只能作「所碍在…」或「不使…为碍」，
  //      不能说「守其人」（人不是可守的对象）。
  // 故按语义分两类：所向=动词（进/守/转/待）可直接带宾语；所阻=名词，只作「所碍在」。
  // 例：所向=守、所阻=心、所需=定 → 「守其行，所碍在心，以求定」
  const clauses = []
  if (going) clauses.push(`欲${going}`)
  if (blocked) clauses.push(`所碍在${blocked}`)
  if (need) clauses.push(`以求${need}`)
  if (!clauses.length) return base
  return `${base}此刻${clauses.join('，')}。`
}

/**
 * 三问是否已答完（三题都选了才算完）。
 * @param {object} answers
 * @returns {boolean}
 */
export function answersComplete(answers) {
  if (!answers) return false
  return QUESTIONS.every((q) => !!answers[q.key])
}