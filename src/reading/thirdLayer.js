/**
 * 解卦文案 · 第三层「想跟你说的话」
 * ========================================
 *
 * 这一层要做的事：用**文言的分寸**说清「现在是什么处境」，
 * 并让读的人觉得「说的是我」，但**不预言、不建议、不编命**。
 *
 * ============================================================================
 * 设计依据（两者缺一不可，改文案前先读）
 * ============================================================================
 *
 * ① 巴纳姆效应（Barnum effect / 福勒效应 Forer effect，1948）
 *    福勒给所有人**同一份**十句通用人格描述，平均契合度评分 **4.26 / 5**。
 *    有效的不是内容，是**句法**：
 *      · 成对结构：「A，却 B」「有时 A，有时 B」「看似 A，实为 B」
 *      · 程度副词与未完成态：可观的、尚未发挥的、许多时候
 *      · 先扬后抑，结尾落在「可弥补的缺点」——认领缺点也不伤自尊
 *      · 只写**可自省的日常经验**，不涉及具体时间、事件、他人
 *    ⭐ 本项目**只取其句法**，不取其欺骗性。
 *
 * ② 易经文体（实测 64 卦，非印象）
 *      · 卦辞**中位仅 12 字**，最短 3 字 —— 省略极彻底，不说满
 *      · 象辞 61/64 命中「X，君子以 Y。」这一固定句式
 *      · 高频字：「以」69 次、「利」58 次、「君子」57 次 —— 模块化到极致
 *      · 结构词恒定：元亨利贞 / 勿 / 无咎 / 往 / 亨 / 贞
 *    ⭐ 文言味不来自生僻词，来自**留白与句式的整齐**。
 *
 * ============================================================================
 * 三段结构
 * ============================================================================
 *   一 · 处境 —— **由卦象推出**（上下卦的自然象关系），不是通用句
 *              这一段是「说得准」的根据：泛泛而谈无法立足，具体才有说服力
 *   二 · 共鸣 —— 福勒式通用句，句法通用、落点克制
 *   三 · 落点 —— 吉则戒骄、凶则劝慰、平则陈述（PRD §4.1.3，不得改）
 *
 * ============================================================================
 * ⚠️ 边界（产品硬约束，写文案时逐条守）
 * ============================================================================
 *   · **不预言**具体时间、事件、他人动向
 *   · **不建议**，不出现「宜 / 不宜 / 你应该 / 建议你」
 *   · **不编造**命定、灾祸、天机
 *   · 共鸣只能来自「描述处境」，**不能来自假装知道用户的私事**
 *     （巴纳姆效应最容易被滥用成后者，那是骗人的，本项目不做）
 *   · 吉卦**戒骄躁**，凶卦固定「运随时变，成事在人」
 *   · 全部标 `ours`（本项目理解），**不得冒充《周易》原文**
 */

import { CROSS_NATURE } from './crossNature.js'

/* ============================================================================
 * 一 · 处境
 * 全部由「上卦自然象 + 下卦自然象」推出。同象、异象各有一句，
 * 64 种组合都能落到具体的画面上，不出现通用套话。
 * ==========================================================================*/

/**
 * 同象：上下同一种自然象 ——「天上有天」这种，画面是**纯粹的强化**。
 * 关键词：纯粹、重复、无杂音 → 处境是「同一种力量在加倍」，好坏人都是极端的。
 */
const SAME_NATURE = {
  天: '天上有天。刚直之气，两重地压下来——你认准的那条路，走得比谁都直，也比谁都孤。',
  地: '地在承地。厚德载物，你扛得住，只是肩上那份常被当成理所当然。',
  山: '山连着山。厚重、笃定、寸步难移；看着不动的人，往往心里最不肯让。',
  水: '水外见水。流行不息，表面柔顺而底下没有一处停过。',
  火: '火外见火。光明外扬，照见别人，也把自己照得无处藏。',
  风: '风相随而动。无孔不入，所以从不断；但风无形，也就无从捉住。',
  雷: '雷声相叠。动则惊人，不动则闷；起落都在一念之间。',
  泽: '泽上承泽。润物无声，善于容納，也最容易被填满而溢。',
}

/** 取象相同的画面（由卦名给出；缺则退回通用句） */
const SAME_BY_HEXAGRAM = {
  乾: '六爻纯阳，刚健到了极点。纯阳则无阴可依，顺而无所畏，顺也就最脆。',
  坤: '六爻纯阴，柔顺到了极点。柔顺则无阳可争，厚而能久，厚也就最闷。',
  震: '长子击雷，动而，其所出者震。雷震百里，而所动者不过一物。',
  巽: '长女入风，入而，其行也巽。风行无形，能入不能留。',
  坎: '水洊至，习坎。重险而能通，因其能从。',
  离: '明两作，离。大明而丽乎万物，继明照四方。',
  艮: '兼山，艮。兼则不重，止则不动，所以能守。',
  兑: '丽泽，兑。相说而悦，是以出命。',
}

/**
 * 推出「处境」一句话。
 * @param {object} r 一卦的数据（data/64卦.json 的一项）
 * @returns {string}
 */
export function situationLine(r) {
  // ① 同象：优先用卦名专属句（有卦名的卦更贴切）
  if (r.upperNature === r.lowerNature) {
    return SAME_BY_HEXAGRAM[r.name] || SAME_NATURE[r.upperNature] || ''
  }
  // ② 异象：用「上象在下象上」的古典句式（56 组，见 crossNature.js）
  const key = `${r.upperNature}在${r.lowerNature}`
  return CROSS_NATURE[key] || `${key}。两象各行其道，你此刻的处境，也是两股力量各自在走。`
}

/** 兜底句的字面量。**verify 里靠它判定「有没有卦落到通用句」**，改文案时别改这里。 */
export const FALLBACK_MARK = '两象各行其道'

/** 这一卦的处境句是不是兜底（调试与验证用） */
export function isFallback(r) {
  return situationLine(r).includes(FALLBACK_MARK)
}

/* ============================================================================
 * 二 · 共鸣（福勒式通用句）
 * 严格用成对句法；只写可自省的日常经验；不涉具体时间、事件、他人。
 * ==========================================================================*/

/**
 * 按吉凶分组的共鸣句。每组四句，轮流取（用卦序决定取哪句，
 * 这样同一卦每次进入看到的是**固定**一句 —— 随机会让同一卦「说法不一」）。
 */
const RESONANCE = {
  吉: [
    '你近来顺，顺得心里反倒有些不安 —— 你比谁都清楚，顺是借来的，不是你的。',
    '你把事情做得很像样，可越像样，越有人替你着急；他们看见的是你看不见的那一处。',
    '你习惯先安排别人，最后才安排自己。这不算美德，只是一个还没改的顺序。',
    '你心里有一件事一直没有真正放下，只是把它推到了「以后」。它在等。',
  ],
  凶: [
    '事情不顺的时候，你多半还在跟人讲道理。可眼下要的不是理，是先过这一段。',
    '你以为再多想一遍就会有答案 —— 有些事是想不通的，只等时间。',
    '你在替一件结果负责，可那结果并不完全由你定。这件事想通，路就松一半。',
    '你撑得住，只是撑得久了。久了的东西会被当成本来就该如此。',
  ],
  平: [
    '你正处在一个不上不下的位置：说坏不坏，说好也不好。这种时候最容易被自己忽略。',
    '你等一个决定，其实是在等一个让自己好过的理由。',
    '你以为事情想不明白是自己笨。有时候只是想不明白而已，不是笨。',
    '你最近的分寸感变好了 —— 你知道什么该急、什么该慢，这在从前不容易。',
  ],
}

/** 用卦序取共鸣句，保证同一卦固定一句 */
export function resonanceLine(r, fortune) {
  const pool = RESONANCE[fortune] || RESONANCE['平']
  return pool[(r.id || 1) % pool.length]
}

/* ============================================================================
 * 三 · 落点（PRD §4.1.3 硬约束，不得改方向）
 * 吉 → 戒骄躁 ／ 凶 → 劝慰「运随时变，成事在人」／ 平 → 中性陈述
 * ==========================================================================*/

const LANDING = {
  吉: '顺的时候最容易走岔 —— 把这份顺当油门，不是终点。',
  凶: '六十四卦排下来，没有一卦能一直难下去。**运随时变，成事在人。**',
  平: '它只是把这件事实话实说。继续观察，不必急着下结论。',
}

export function landingLine(fortune) {
  return LANDING[fortune] || LANDING['平']
}

/**
 * 组装第三层全文。
 *
 * @param {object} r       一卦数据
 * @param {string} fortune '吉' | '凶' | '平'
 * @param {object} opts    { simple: boolean } —— simple=true 时只给「处境 + 落点」，
 *                         用于界面空间有限处（不含共鸣段）
 * @returns {{situation:string, resonance:string, landing:string, full:string}}
 */
export function buildThirdLayer(r, fortune, opts = {}) {
  const situation = situationLine(r)
  const resonance = opts.simple ? '' : resonanceLine(r, fortune)
  const landing = landingLine(fortune)
  const parts = [situation, resonance, landing].filter(Boolean)
  return { situation, resonance, landing, full: parts.join('\n\n') }
}

/** 只有落点时的短句（用于结果页空间有限处 / 记录页摘要） */
export function shortLine(fortune) {
  return landingLine(fortune)
}