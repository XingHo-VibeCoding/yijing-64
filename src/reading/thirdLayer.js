/**
 * 按卦序取共鸣句，保证同一卦固定一句。
 *
 * ⚠️ 用**黄金比例散列**而不是 `id % pool.length`：实测 `id % 10` 在 64 卦上分布很偏
 *    —— 「平」16 卦漏掉 1 句、「凶」9 卦漏掉 4 句，30 句里只有 25 句会被用到，
 *    而漏掉的那几句等于白写。散列把 id 打散到整个池子，分布均匀得多。
 *    （`黄金比例 0.618` 是散列的经验常数，与内容无关，纯为打散。）
 */
export function resonanceLine(r, fortune) {
  const pool = RESONANCE[fortune] || RESONANCE['平']
  const n = pool.length
  const h = Math.floor((r.id || 1) * 0.6180339887)
  return pool[((h % n) + n) % n]
}

/* ============================================================================
 * 三 · 落点（PRD §4.1.3 硬约束，不得改方向）
 * 吉 → 戒骄躁 ／ 凶 → 劝慰「运随时变，成事在人」／ 平 → 中性陈述
 * ==========================================================================*/

const LANDING = {
  吉: '顺的时候最容易走岔 —— 把这份顺当油门，不是终点。',
  凶: '六十四卦排下来，没有一卦能一直难下去。**运随时变，成事在人。**',
  平: '它只是把这件事实话实说。继续观察，不必急着下结论。',
}

export function landingLine(fortune) {
  return LANDING[fortune] || LANDING['平']
}

/**
 * 组装第三层全文。
 *
 * @param {object} r       一卦数据
 * @param {string} fortune '吉' | '凶' | '平'
 * @param {object} opts    { simple: boolean } —— simple=true 时只给「处境 + 落点」，
 *                         用于界面空间有限处（不含共鸣段）
 * @returns {{situation:string, resonance:string, landing:string, full:string}}
 */
export function buildThirdLayer(r, fortune, opts = {}) {
  const situation = situationLine(r)
  const resonance = opts.simple ? '' : resonanceLine(r, fortune)
  const landing = landingLine(fortune)
  const parts = [situation, resonance, landing].filter(Boolean)
  return { situation, resonance, landing, full: parts.join('\n\n') }
}

/** 只有落点时的短句（用于结果页空间有限处 / 记录页摘要） */
export function shortLine(fortune) {
  return landingLine(fortune)
}