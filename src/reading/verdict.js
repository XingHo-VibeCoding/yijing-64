/**
 * 每日卦象短评。
 *
 * ⚠️ **不做随机抽取**：同一卦每次返回**固定**一句。
 *    - 「让用户觉得精准」的关键是**同一卦每次说法一致** ——
 *      今天看泰卦说「小往大来，其道光明」，明天再看到就得是同一句。
 *      若每次不同，用户会察觉「系统在编」，而这恰恰是最伤体验的地方。
 *    - 变化感由「换一卦」自然提供，不需要在同一卦内摇摆。
 *
 * @param {object} r 一卦的数据（data/64卦.json 的一项），需含 id
 * @returns {string} ≤30 字；无专属句时返回空串（界面据此隐藏该行，不填兜底）
 */
export function verdictLine(r) {
  if (!r || !r.id) return ''
  return VERDICT[r.id] || ''
}

/**
 * 是否存在专属短评（界面据此决定要不要渲染这一行）。
 * @param {object} r
 * @returns {boolean}
 */
export function hasVerdict(r) {
  return !!verdictLine(r)
}