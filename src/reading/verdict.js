/**
 * 每日卦象解读 · 骈句短评（记录页用）
 *
 * ============================================================================
 * 设计依据（四条，全部有据）
 * ============================================================================
 *
 * ① **为什么是「预制库」而不是「每次随机生成」**
 *    - 30 字是**硬上限**。随机生成后再数字数，超了要重抽 → 做不到稳定。
 *    - 骈句要**对仗工整**。临时组句只能凑字数，对仗与用典基本不可能工整。
 *    - 边界要**上线前能扫**：禁「宜 / 不宜 / 你会 / 命定」等词，
 *      随机生成必会偶发越界，且事后无从查证。
 *    - 验收要**能断言**。项目规则要求「逐项有证据」，每次都变的文案没法写进验收表。
 *    → 故采用预制库：写库时逐句校验字数与禁词。
 *
 * ② **为什么是「骈句」而不是散文**
 *    实测 64 卦卦辞：**中位仅 12 字、最短 3 字** —— 省略极彻底，不说满。
 *    骈句（对偶）天然短、节奏齐、留白多，正是这个语体的外形。
 *    例：「天行健，君子以自强不息」式的两段并列，读者一眼认得出是文言。
 *
 * ③ **为什么必须「积极」**
 *    产品边界：吉卦戒骄、凶卦劝慰，**不给宿命**。
 *    所以每句的落点都在**人**身上（可做的事），不在**命**上（会发生的事）。
 *    凶卦不写「将败」，写「此时守，比此时进更难」；不写「注定」，写「尚可为」。
 *
 * ④ **「精准」从哪来**
 *    不是假装知道用户的私事（那是骗人），而是**从卦象推出处境**：
 *    每句都扣住该卦的自然象或卦辞里的具体字眼。
 *    例：蹇（水在山上，往险）→「水在山上难行；退一步不是输，是省力。」
 *
 * ============================================================================
 * ⚠️ 改之前必读 —— 两处踩过的坑
 * ============================================================================
 *
 * **(1) 卦序必须与 `data/64卦.json` 逐条核对，不能凭记忆写。**
 *     本项目数据用的是**通行本序**（6=讼、9=小畜、11=泰、60=节），
 *     我曾按「乾屯蒙需讼师比」的另一种排法写，结果 20 余条卦名对不上。
 *     ⇒ 改完必跑 `node scripts/verify-verdict.mjs`，它会按数据逐条对卦名。
 *
 * **(2) 分隔注释必须闭合。**
 *     形如「斜杠星号 + 一串等号 + 星号斜杠」的分隔注释，若漏了收尾的星号斜杠，
 *     **后面整块（含数据）会被当成注释吞掉**，而 Node 有时报语法错、有时不报
 *     ——只是 `export` 少了那个键，症状极难定位。写完先 `node --check` 看一眼。
 *
 * ============================================================================
 * 硬约束（改完必跑 `node scripts/verify-verdict.mjs`）
 * ============================================================================
 *   - 每句 **≤ 30 字**（脚本按汉字计数，标点不计）
 *   - 禁词：宜 / 不宜 / 建议你 / 命定 / 天机 / 必然 / 注定 / 一定能
 *   - 不出现对未来的断言（「你会…」后接断言词即违规；「你会发现」这类中性用法不算）
 *   - 64 卦**各有专属一句**，无通用兜底、无重复句
 */

